export function stripSchoolNameMarks(name) {
  return String(name || "").replace(MARK_RE, "").trim();
}

export function normalizeSchoolKey(name) {
  return stripSchoolNameMarks(name)
    .replace(/[（）]/g, (ch) => (ch === "（" ? "(" : ")"))
    .replace(/\s+/g, "")
    .trim();
}

/**
 * 把展示名对到官方全称。对不上则返回空字符串。
 * 括号校区（如哈尔滨工业大学(深圳)）归到本部；
 * 「东南大学成贤学院」「南昌大学共青学院」等不归到本部。
 */
export function canonicalSchoolName(name) {
  const raw = normalizeSchoolKey(name);
  if (!raw || NO_MARK_RE.test(raw)) return "";
  if (INDEPENDENT_COLLEGE_RE.test(raw)) return "";
  if (SCHOOL_ALIASES[raw]) return SCHOOL_ALIASES[raw];
  if (OFFICIAL_985_SET.has(raw) || OFFICIAL_211_SET.has(raw)) return raw;

  const m = raw.match(/^(.+?)\((.+)\)(.*)$/);
  if (m) {
    const baseRaw = m[1];
    const base = SCHOOL_ALIASES[baseRaw] || baseRaw;
    if (OFFICIAL_985_SET.has(base) || OFFICIAL_211_SET.has(base)) return base;
  }
  // 无括号的校区/分校写法，如「合肥工业大学宣城校区」。不以「学院」冒充本部。
  const campus = raw.match(/^(.+?)([^学院]{1,8}(?:校区|分校))$/);
  if (campus) {
    const base = SCHOOL_ALIASES[campus[1]] || campus[1];
    if (OFFICIAL_985_SET.has(base) || OFFICIAL_211_SET.has(base)) return base;
  }
  return "";
}

export function schoolNameTier(name) {
  const canon = canonicalSchoolName(name);
  if (!canon) return "other";
  if (OFFICIAL_985_SET.has(canon)) return "u985";
  if (OFFICIAL_211_SET.has(canon)) return "u211";
  return "other";
}

export function is985Name(name) {
  return schoolNameTier(name) === "u985";
}

/** 含 985。判断「是否 211 工程高校」。 */
export function is211Name(name) {
  const t = schoolNameTier(name);
  return t === "u985" || t === "u211";
}

/** 返回 ★、▲ 或空字符串。985 只返回 ★。 */
export function universityMark(name) {
  const t = schoolNameTier(name);
  if (t === "u985") return SCHOOL_NAME_MARK.u985;
  if (t === "u211") return SCHOOL_NAME_MARK.u211;
  return "";
}

/**
 * 统一的院校名展示。保留原称号（简称仍用简称），只加一个前缀。
 * 重复调用不会堆前缀。非录取文案（未录取、专科占位、无、暂缺）不加标记。
 */
export function formatSchoolName(name) {
  if (name == null) return "";
  const text = String(name).trim();
  if (!text) return "";
  const bare = stripSchoolNameMarks(text);
  if (!bare) return "";
  if (NO_MARK_RE.test(normalizeSchoolKey(bare))) return bare;
  const mark = universityMark(bare);
  return mark ? mark + bare : bare;
}

