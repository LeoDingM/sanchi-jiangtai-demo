export function generateName(rng, used, gender) {
  const pool = gender === "F" ? GIVEN_F : GIVEN_M;
  for (let i = 0; i < 120; i++) {
    const name = pick(rng, SURNAMES) + pick(rng, pool);
    if (!used.has(name)) {
      used.add(name);
      return name;
    }
  }
  const name = pick(rng, SURNAMES) + pick(rng, pool) + pick(rng, ["甲","乙","丙","丁","戊"]);
  used.add(name);
  return name;
}
